/* ============================================================
 * 安全审查插件 —— 骨架
 * ------------------------------------------------------------
 * 当前只是一个占位：面板能打开、标签能切换，内容待接入。
 *
 * 挂载点说明（对应内核 _core/ui.js 的 rebuild()）：
 *   - 启用后，「插件管理」里会出现一行带开关的条目
 *   - 同时多出一个「安全审查」标签页，内容由下面的 settings() 返回
 *   - settings() 每次打开该标签页都会被重新调用，不用自己做缓存
 * ============================================================ */
'use strict';

var ctx = null;

function enable(c) {
    ctx = c;
    ctx.log('安全审查已启用');
}

function disable() {
    if (ctx) ctx.log('安全审查已关闭');
}

/* ------------------------------------------------------------
 * 面板内容 —— 待实现
 * 返回一个 DOM 节点（c.ui.el / c.ui.section 产出的都行）
 * ---------------------------------------------------------- */
function settings(c) {
    var wrap = c.ui.el('div');

    wrap.appendChild(c.ui.note(
        '安全审查面板 —— 内容待接入。<br>' +
        '当前仅占位，点标签能正常打开。'
    ));

    return wrap;
}

module.exports = {
    enable: enable,
    disable: disable,
    settings: settings
};
